static const unsigned char	g_o11[] = {0x29, 0x32}; /* "sh" */

static const struct s_obf
{
	const unsigned char	*b;
	size_t			n;
}	g_tab[] = {
	{g_o0, 9}, {g_o1, 3}, {g_o2, 1}, {g_o3, 1}, {g_o4, 5}, {g_o5, 4},
	{g_o6, 12}, {g_o7, 33}, {g_o8, 22}, {g_o9, 28}, {g_o10, 7}, {g_o11, 2},
};

char	*str_dec(int id, char *out)
{
	const unsigned char	*b;
	size_t			n;
	size_t			i;

	b = g_tab[id].b;
	n = g_tab[id].n;
	i = 0;
	while (i < n)
	{
		out[i] = (char)(b[i] ^ STR_KEY);
		i++;
	}
	out[i] = '\0';
	return (out);
}
