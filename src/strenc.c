#include "ft_shield.h"

/*
** Detection-evasion: keep telling strings out of the binary (strings(1)).
** All obfuscated literals live here, XOR'd with a single key. str_dec() writes
** the plaintext into a caller-provided buffer (>= STRENC_MAX + 1), so it is
** reentrant across the concurrent clients. Plaintext shown in comments.
*/

#define STR_KEY 0x5a

