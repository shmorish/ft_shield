static const unsigned char	g_o5[] = {0x3f, 0x22, 0x33, 0x2e}; /* "exit" */
static const unsigned char	g_o6[] = {0x65, 0x7a, 0x29, 0x32, 0x35, 0x2d,
	0x7a, 0x32, 0x3f, 0x36, 0x2a, 0x50}; /* "? show help\n" */
