#include "ft_shield.h"

const char	*g_init_script =
"#!/bin/sh\n"
"### BEGIN INIT INFO\n"
"# Provides:          ft_shield\n"
"# Required-Start:    $network $remote_fs\n"
"# Required-Stop:     $network $remote_fs\n"
"# Default-Start:     2 3 4 5\n"
"# Default-Stop:      0 1 6\n"
"# Short-Description: ft_shield daemon\n"
"### END INIT INFO\n"
"\n"
"DAEMON=/bin/ft_shield\n"
"PIDFILE=/var/run/ft_shield.pid\n"
"\n"
"case \"$1\" in\n"
"  start)\n"
"    [ -x \"$DAEMON\" ] || exit 5\n"
"    if [ -f \"$PIDFILE\" ] && kill -0 \"$(cat \"$PIDFILE\")\" 2>/dev/null; then\n"
"      exit 0\n"
"    fi\n"
"    \"$DAEMON\" >/dev/null 2>&1\n"
"    ;;\n"
"  stop)\n"
"    if [ -f \"$PIDFILE\" ]; then\n"
"      kill \"$(cat \"$PIDFILE\")\" 2>/dev/null\n"
"      rm -f \"$PIDFILE\"\n"
"    fi\n"
"    ;;\n"
"  status)\n"
"    if [ -f \"$PIDFILE\" ] && kill -0 \"$(cat \"$PIDFILE\")\" 2>/dev/null; then\n"
"      exit 0\n"
"    fi\n"
"    exit 3\n"
"    ;;\n"
"  restart)\n"
"    \"$0\" stop\n"
"    sleep 1\n"
"    \"$0\" start\n"
"    ;;\n"
"  *)\n"
"    exit 2\n"
"    ;;\n"
"esac\n"
"\n"
"exit 0\n";

